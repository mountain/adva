#!/usr/bin/env python3
"""The first Futamura projection with dynamic residuals, executed.

The previous calibration compiled a fully static source family, so every residual was
a constant. This one keeps a dynamic input alive: the source language is the declared
subset of the machine's own instruction language (`input d`, `return s`, two slots,
fixed length three), the source program is the static part, and the object input value
`x` is the dynamic part. The residual therefore has to be *code*, not a constant.

- `I` is the declared subset interpreter generated by the scaling preflight
  (`experiments/self_interpretation_scaling/check.py`), reused unchanged here for the
  length it was generated at.
- `C` is the compiler, generated in this file: it reads an encoded source program as
  data, keeps the last instruction that writes the returned slot, drops every other
  instruction, and emits the residual program in the same declared encoding it read.
- The residual is instantiated into a real program and executed directly on `x`.

Declared rule for this compiler: the returned slot's last writer is kept, together
with the return; every other instruction is dropped. Nothing else is optimised, and
the source-to-residual rule is one sentence because it has to be checkable by reading
it.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys
import tarfile

MAX_LAUNCHES = 96
FUEL = 2048
QUANTUM = 2048

SCALING = pathlib.Path(__file__).resolve().parents[1] / "self_interpretation_scaling/check.py"
SPEC = importlib.util.spec_from_file_location("scaling_check", SCALING)
SCALING_CHECK = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SCALING_CHECK)

INPUT_TAG = SCALING_CHECK.TAG["input"]
RETURN_TAG = SCALING_CHECK.TAG["return"]
PROGRAM_TAG = SCALING_CHECK.OBJECT_PROGRAM_TAG
SOURCE_LENGTH = 3
RESIDUAL_REGISTERS = [("s0", "data"), ("s1", "data")]

# Compiler register file.
BUNDLE, PROGRAM, INSTR, TMP, EMIT_A, EMIT_B = 0, 1, 2, 3, 4, 5
OPCODE, OPERAND, TARGET, PROBE = 6, 7, 8, 9
TEST, HAVE = 10, 11
COMPILER_REGISTERS = [
    ("bundle", "data"), ("program", "data"), ("instr", "data"), ("tmp", "data"),
    ("emit_a", "data"), ("emit_b", "data"), ("opcode", "integer"), ("operand", "integer"),
    ("target", "integer"), ("probe", "integer"), ("test", "boolean"), ("have", "boolean"),
]


def compiler_program() -> dict:
    """Generate the compiler: read the program as data, emit the residual as data."""
    code: list[dict] = []

    def emit(instruction: dict) -> int:
        code.append(instruction)
        return len(code) - 1

    def field(src: int, arity: int, index: int, dst: int) -> None:
        emit({"op": "field", "src": src, "arity": arity, "index": index, "dst": dst})

    emit({"op": "input", "dst": BUNDLE})
    field(BUNDLE, 2, 0, PROGRAM)                       # the static source program
    field(PROGRAM, SOURCE_LENGTH, 2, INSTR)            # the return instruction
    emit({"op": "tag", "src": INSTR, "dst": OPCODE})
    emit({"op": "constant", "dst": PROBE, "value": RETURN_TAG})
    emit({"op": "equal", "left": OPCODE, "right": PROBE, "dst": TEST})
    in_family = emit({"op": "branch", "condition": TEST, "yes": len(code) + 1, "no": 0})
    field(INSTR, 1, 0, TMP)
    emit({"op": "as_integer", "src": TMP, "dst": TARGET})   # the returned slot
    # `have` starts false: 0 = 1 is false, and no boolean constant instruction exists.
    emit({"op": "constant", "dst": PROBE, "value": 0})
    emit({"op": "constant", "dst": OPERAND, "value": 1})
    emit({"op": "equal", "left": PROBE, "right": OPERAND, "dst": HAVE})

    # One unrolled case per earlier instruction: does it write the returned slot?
    for index in range(SOURCE_LENGTH - 1):
        field(PROGRAM, SOURCE_LENGTH, index, INSTR)
        emit({"op": "tag", "src": INSTR, "dst": OPCODE})
        emit({"op": "constant", "dst": PROBE, "value": INPUT_TAG})
        emit({"op": "equal", "left": OPCODE, "right": PROBE, "dst": TEST})
        not_input = emit({"op": "branch", "condition": TEST,
                          "yes": len(code) + 1, "no": 0})
        field(INSTR, 1, 0, TMP)
        emit({"op": "as_integer", "src": TMP, "dst": OPERAND})
        emit({"op": "equal", "left": OPERAND, "right": TARGET, "dst": TEST})
        comes_next = emit({"op": "branch", "condition": TEST,
                           "yes": len(code) + 1, "no": 0})
        emit({"op": "equal", "left": PROBE, "right": PROBE, "dst": HAVE})  # have := true
        code[not_input]["no"] = len(code)
        code[comes_next]["no"] = len(code)

    # Emission: the return instruction always; the writer instruction only if one exists.
    emit({"op": "box_integer", "src": TARGET, "dst": TMP})
    emit({"op": "node", "tag": RETURN_TAG, "fields": [TMP], "dst": EMIT_B})
    emit({"op": "node", "tag": INPUT_TAG, "fields": [TMP], "dst": EMIT_A})
    emit({"op": "branch", "condition": HAVE, "yes": len(code) + 1, "no": 0})
    with_writer = len(code) - 1
    emit({"op": "node", "tag": PROGRAM_TAG, "fields": [EMIT_A, EMIT_B], "dst": TMP})
    emit({"op": "return", "src": TMP})
    code[with_writer]["no"] = len(code)
    emit({"op": "node", "tag": PROGRAM_TAG, "fields": [EMIT_B], "dst": TMP})
    emit({"op": "return", "src": TMP})

    # The declared refusal for a program outside the handled family.
    code[in_family]["no"] = len(code)
    emit({"op": "reject", "reason": "source program is outside the handled family"})
    return {
        "schema": "adva.data-machine.program.research.v0",
        "name": "futamura-residual-compiler",
        "registers": [{"name": n, "kind": k} for n, k in COMPILER_REGISTERS],
        "code": code,
    }


def source_program(first: int, second: int, returned: int) -> dict:
    """A source program in the declared subset: input, input, return."""
    return {"kind": "node", "tag": PROGRAM_TAG,
            "fields": [SCALING_CHECK.object_instruction(INPUT_TAG, [first]),
                       SCALING_CHECK.object_instruction(INPUT_TAG, [second]),
                       SCALING_CHECK.object_instruction(RETURN_TAG, [returned])]}


def source_bundle(program: dict, dynamic: int) -> dict:
    return {"kind": "node", "tag": SCALING_CHECK.BUNDLE_TAG,
            "fields": [program, {"kind": "integer", "value": dynamic}]}


def _decode(residual: dict) -> list[dict]:
    code = []
    for instruction in residual["fields"]:
        tag = instruction["tag"]
        operands = [field["value"] for field in instruction["fields"]]
        if tag == INPUT_TAG:
            code.append({"op": "input", "dst": operands[0]})
        elif tag == RETURN_TAG:
            code.append({"op": "return", "src": operands[0]})
        else:
            raise SystemExit(f"residual instruction tag {tag} is outside the declared encoding")
    return code


class Runner:
    def __init__(self, binary: str, workdir: pathlib.Path):
        self.binary = binary
        self.workdir = workdir
        self.launches = 0

    def run(self, name: str, prog: dict, data: dict) -> dict:
        if self.launches >= MAX_LAUNCHES:
            raise SystemExit(f"launch budget of {MAX_LAUNCHES} exhausted at {name}")
        self.launches += 1
        program_path = self.workdir / "raw" / "programs" / f"{name}.adva"
        input_path = self.workdir / "raw" / "inputs" / f"{name}.json"
        output_path = self.workdir / "raw" / "runs" / f"{name}.run.adva"
        for parent in (program_path.parent, input_path.parent, output_path.parent):
            parent.mkdir(parents=True, exist_ok=True)
        program_path.write_text(json.dumps(prog, indent=2) + "\n")
        input_path.write_text(json.dumps(data, indent=2) + "\n")
        done = subprocess.run(
            [self.binary, "data-run", str(program_path), "--input", str(input_path),
             "--fuel", str(FUEL), "--quantum", str(QUANTUM), "--output", str(output_path)],
            check=False, capture_output=True, text=True, timeout=20,
        )
        observed = {"exit_code": done.returncode, "stderr": done.stderr.strip()}
        if output_path.exists():
            record = json.loads(output_path.read_text())
            phase = record["state"].get("phase", {})
            observed.update({
                "status": record["status"],
                "steps": len(record["trace"]),
                "value": (phase.get("value") or {}).get("value"),
                "phase_reason": phase.get("reason"),
            })
        return observed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--binary", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    out = pathlib.Path(args.output)
    if out.exists() and any(out.iterdir()):
        raise SystemExit(f"{out} already holds a retained attempt; choose a new directory")
    out.mkdir(parents=True, exist_ok=True)

    interpreter = SCALING_CHECK.meta_program(["input", "return"], SOURCE_LENGTH)
    compiler = compiler_program()
    (out / "interpreter.adva").write_text(json.dumps(interpreter, indent=2) + "\n")
    (out / "compiler.adva").write_text(json.dumps(compiler, indent=2) + "\n")

    runner = Runner(args.binary, out)
    cases = []
    failures = []
    for first in (0, 1):
        for second in (0, 1):
            for returned in (0, 1):
                program = source_program(first, second, returned)
                label = f"p{first}{second}{returned}"
                compiled = runner.run(f"{label}.compiled", compiler, source_bundle(program, 0))
                if compiled.get("status") != "Returned":
                    failures.append(f"{label}: the compiler did not return: {compiled}")
                    continue
                record = json.loads(
                    (out / "raw" / "runs" / f"{label}.compiled.run.adva").read_text())
                residual = record["state"]["phase"]["value"]
                (out / "residuals").mkdir(exist_ok=True)
                (out / "residuals" / f"{label}.json").write_text(
                    json.dumps(residual, indent=2) + "\n")
                residual_program = {
                    "schema": "adva.data-machine.program.research.v0",
                    "name": "futamura-dynamic-residual",
                    "registers": [{"name": n, "kind": k} for n, k in RESIDUAL_REGISTERS],
                    "code": _decode(residual),
                }
                for dynamic in (7, 9):
                    interpreted = runner.run(
                        f"{label}.interpreted.{dynamic}", interpreter,
                        source_bundle(program, dynamic))
                    direct = runner.run(
                        f"{label}.residual.{dynamic}", residual_program,
                        {"kind": "integer", "value": dynamic})
                    row = {
                        "case": label,
                        "source": [first, second, returned],
                        "dynamic": dynamic,
                        "interpreted_status": interpreted.get("status"),
                        "interpreted_value": interpreted.get("value"),
                        "interpreted_steps": interpreted.get("steps"),
                        "residual_status": direct.get("status"),
                        "residual_value": direct.get("value"),
                        "residual_steps": direct.get("steps"),
                        "compile_steps": compiled.get("steps"),
                        "residual_instructions": len(residual_program["code"]),
                        "source_instructions": SOURCE_LENGTH,
                    }
                    cases.append(row)
                    agree = (row["interpreted_status"] == row["residual_status"]
                             and row["interpreted_value"] == row["residual_value"])
                    if not agree:
                        failures.append(f"{label} x={dynamic}: disagreement: {row}")
                    else:
                        written = returned in (first, second)
                        if written and row["residual_value"] != dynamic:
                            failures.append(f"{label} x={dynamic}: expected {dynamic}: {row}")
                        if not written and row["residual_status"] != "Rejected":
                            failures.append(f"{label} x={dynamic}: expected a refusal: {row}")

    sizes = sorted({c["residual_instructions"] for c in cases})
    gains = [{"case": c["case"], "dynamic": c["dynamic"],
              "interpreted_steps": c["interpreted_steps"],
              "residual_steps": c["residual_steps"],
              "compile_steps": c["compile_steps"]} for c in cases]
    record = {
        "schema": "adva.futamura-dynamic-residual.result.v0",
        "source_language": "input d, return s; two data slots; source programs are exactly input, input, return",
        "compiler": {
            "instructions": len(compiler["code"]),
            "registers": len(compiler["registers"]),
            "rule": "keep the last instruction that writes the returned slot, together with the return; drop every other instruction",
            "rejects": "a source program whose third instruction is not a return is refused by the compiler itself",
        },
        "interpreter": {"instructions": len(interpreter["code"]), "source": "self_interpretation_scaling/check.py, reused unchanged"},
        "residual_instruction_counts": sizes,
        "cases": cases,
        "gains": gains,
        "launches": runner.launches,
        "failures": failures,
        "verdict": "Passed" if not failures else "Failed",
    }
    raw = out / "raw"
    digests = {}
    archive = out / "attempt.tar.gz"
    with tarfile.open(archive, "w:gz") as bundle:
        for path in sorted(raw.rglob("*")):
            if path.is_file():
                relative = str(path.relative_to(raw))
                bundle.add(path, arcname=relative)
                digests[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    with tarfile.open(archive, "r:gz") as check:
        for member in check.getmembers():
            if member.isfile():
                assert hashlib.sha256(check.extractfile(member).read()).hexdigest() \
                    == digests[member.name], f"archive digest mismatch for {member.name}"
    shutil.rmtree(raw)
    record["retained"] = {
        "archive": archive.name,
        "archive_files": len(digests),
        "archive_bytes": archive.stat().st_size,
        "archive_digests_verified": True,
        "loose": "interpreter.adva, compiler.adva, results.json and residuals/",
    }
    (out / "results.json").write_text(json.dumps(record, indent=2) + "\n")

    print("compiler                     :", len(compiler["code"]), "instructions,",
          len(compiler["registers"]), "registers")
    print("interpreter (reused)         :", len(interpreter["code"]), "instructions")
    print("residual instruction counts  :", sizes)
    print("source instructions          :", SOURCE_LENGTH)
    print("cases                        :", len(cases))
    print("interpreted steps min/max    :",
          min(c["interpreted_steps"] for c in cases if c["interpreted_steps"]),
          max(c["interpreted_steps"] for c in cases if c["interpreted_steps"]))
    print("residual steps min/max       :",
          min(c["residual_steps"] for c in cases if c["residual_steps"]),
          max(c["residual_steps"] for c in cases if c["residual_steps"]))
    print("retained                     :", record["retained"])
    print("launches                     :", runner.launches, f"(budget {MAX_LAUNCHES})")
    print("verdict                      :", record["verdict"])
    for failure in failures[:6]:
        print("  FAIL", failure)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
